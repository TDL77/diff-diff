import numpy as np
import pytest

from diff_diff.linalg import (
    _compute_bm_dof_oneway,
    _compute_cr2_bm,
    _compute_cr2_bm_contrast_dof,
    _compute_hat_diagonals,
)

_FIXTURE_PATH = os.path.join(
    os.path.dirname(__file__),
    "..",
    "benchmarks",
    "data",
    "clubsandwich_cr2_golden.json",
)
_R_FIXTURE_AVAILABLE = os.path.exists(_FIXTURE_PATH)


@pytest.fixture(scope="module")
def goldens():
    if not _R_FIXTURE_AVAILABLE:
        pytest.skip(
            "clubsandwich_cr2_golden.json not generated; run "
            "Rscript benchmarks/R/generate_clubsandwich_golden.R"
        )
    with open(_FIXTURE_PATH) as f:
        return json.load(f)


def _design_x_z(d):
    """Build [1, x, z] design matrix from a golden scenario dict."""
    return np.column_stack([np.ones(len(d["x"])), np.asarray(d["x"]), np.asarray(d["z"])])


def _refit_wls(X, y, w):
    """Refit WLS to obtain coef and residuals consistent with R's lm()."""
    bread = X.T @ (X * w[:, None])
    coef = np.linalg.solve(bread, X.T @ (w * y))
    return coef, y - X @ coef, bread


class TestWLSCR2ParityClubSandwich:
    """Parity for weighted CR2 Bell-McCaffrey against clubSandwich's WLS-CR2."""

    def test_one_way_weighted_hc2_bm_se_matches_clubsandwich(self, goldens):
        d = goldens["weighted_one_way_no_cluster"]
        X = _design_x_z(d)
        y = np.asarray(d["y"])
        w = np.asarray(d["weights"])
        coef, resid, bread = _refit_wls(X, y, w)
        _compute_hat_diagonals(X, bread, weights=w)
        # One-way (no cluster) HC2-BM SE via the diff-diff dispatcher.
        # Per the lifted gate, _compute_bm_dof_oneway returns the DOF; the SE
        # is sqrt(diag(vcov)) where vcov is computed in `_compute_robust_vcov_numpy`.
        # We pin both the vcov (via R's vcov_hc2_bm) and the DOF here.
        r_vcov = np.asarray(d["vcov_hc2_bm"]).reshape(d["vcov_hc2_bm_shape"])
        r_se = np.asarray(d["se_hc2_bm"])
        r_dof = np.asarray(d["dof_bm_one_way"])

        # Use the public dispatcher path
        from diff_diff.linalg import compute_robust_vcov

        vcov, dof = compute_robust_vcov(
            X,
            resid,
            vcov_type="hc2_bm",
            weights=w,
            weight_type="pweight",
            return_dof=True,
        )
        np.testing.assert_allclose(
            vcov,
            r_vcov,
            atol=1e-10,
            rtol=1e-10,
            err_msg="weighted one-way HC2-BM vcov should match clubSandwich",
        )
        np.testing.assert_allclose(
            np.sqrt(np.diag(vcov)),
            r_se,
            atol=1e-10,
            err_msg="weighted one-way HC2-BM SE should match clubSandwich",
        )
        np.testing.assert_allclose(
            dof, r_dof, atol=1e-10, err_msg="weighted one-way HC2-BM DOF should match clubSandwich"
        )

    def test_balanced_clusters_weighted_cr2_se(self, goldens):
        d = goldens["weighted_balanced_clusters"]
        X = _design_x_z(d)
        y = np.asarray(d["y"])
        w = np.asarray(d["weights"])
        cluster_ids = np.asarray(d["cluster"])
        coef, resid, bread = _refit_wls(X, y, w)
        r_vcov = np.asarray(d["vcov_cr2"]).reshape(d["vcov_cr2_shape"])
        r_dof = np.asarray(d["dof_bm"])

        vcov, dof = _compute_cr2_bm(X, resid, cluster_ids, bread, weights=w)
        np.testing.assert_allclose(vcov, r_vcov, atol=1e-10)
        np.testing.assert_allclose(dof, r_dof, atol=1e-10)

    def test_unbalanced_clusters_weighted_cr2_dof(self, goldens):
        d = goldens["weighted_unbalanced_clusters"]
