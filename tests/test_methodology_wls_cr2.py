class TestDOFFormulaDualPathEquivalence:
    """Dual-path equivalence: the existing simple (tr B)^2 / tr(B^2) formula
    must agree with the new full P_array form at the unweighted limit.

    This addresses the reviewer's MEDIUM #2 concern about parallel DOF formulas
    drifting over time. The new P_array form is only used when weights is
    not None; the unweighted path keeps the simple formula. At the unweighted
    limit (weights=ones), both formulas mathematically reduce to the same
    Pustejovsky-Tipton (2018) Theorem 1 value, and this test pins their
    numerical agreement.
    """

    def test_unweighted_dof_path_equivalence(self, goldens):
        d = goldens["unbalanced_medium"]
        X = np.column_stack([np.ones(len(d["x"])), np.asarray(d["x"])])
        y = np.asarray(d["y"])
        cluster_ids = np.asarray(d["cluster"])
        bread = X.T @ X
        coef = np.linalg.solve(bread, X.T @ y)
        resid = y - X @ coef

        # Path A: unweighted simple formula (weights=None).
        _, dof_simple = _compute_cr2_bm(X, resid, cluster_ids, bread, weights=None)
        # Path B: P_array formula via weights=ones (forces weighted branch).
        n = X.shape[0]
        w_ones = np.ones(n)
        _, dof_p_array = _compute_cr2_bm(X, resid, cluster_ids, bread, weights=w_ones)
        np.testing.assert_allclose(
            dof_simple,
            dof_p_array,
            atol=1e-12,
            err_msg=(
                "At the unweighted limit, the simple (tr B)^2/tr(B^2) and the "
                "full P_array formulas must agree. Drift indicates the P_array "
                "implementation has a bug (likely chol direction or M_U "
                "normalization)."
            ),
        )

    def test_unweighted_one_way_dof_path_equivalence(self, goldens):
        d = goldens["singletons_present"]
        X = np.column_stack([np.ones(len(d["x"])), np.asarray(d["x"])])
        y = np.asarray(d["y"])
        bread = X.T @ X
        coef = np.linalg.solve(bread, X.T @ y)
        y - X @ coef
        h_diag = _compute_hat_diagonals(X, bread, weights=None)

        # Path A: unweighted simple formula.
        dof_simple = _compute_bm_dof_oneway(X, bread, h_diag, weights=None)
        # Path B: P_array via singleton-cluster reduction with weights=ones.
        n = X.shape[0]
        w_ones = np.ones(n)
        h_diag_ones = _compute_hat_diagonals(X, bread, weights=w_ones)
        dof_p_array = _compute_bm_dof_oneway(X, bread, h_diag_ones, weights=w_ones)
        np.testing.assert_allclose(
            dof_simple,
            dof_p_array,
            atol=1e-12,
            err_msg=(
                "One-way unweighted DOF: simple formula must agree with the "
                "P_array singleton-cluster reduction at the unweighted limit."
            ),
        )
