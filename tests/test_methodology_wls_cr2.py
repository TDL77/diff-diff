"""Parity tests for WLS-CR2 Bell-McCaffrey against clubSandwich R goldens.

This file pins `diff_diff/linalg.py`'s weighted CR2-BM port against
`clubSandwich::vcovCR(lm(weights=w), type="CR2") + coef_test(test=
"Satterthwaite")$df_Satt` plus the compound-contrast DOF from
`Wald_test(constraints=matrix(c, 1), test="HTZ")$df_denom` (which on a 1-row
constraint matrix reduces to a Satterthwaite t-test).

Goldens are generated by `benchmarks/R/generate_clubsandwich_golden.R` (six
new weighted scenarios appended in this PR; existing six unweighted scenarios
unchanged for regression safety).

Algorithm note: clubSandwich's WLS-CR2 algebra is NOT a textbook
Pustejovsky-Tipton (2018) §3.3 transform-once derivation — the two diverge by
0.5-30% on weighted designs (see `feedback_wls_cr2_clubsandwich_parity`).
clubSandwich uses W (not sqrt(W)) in the hat matrix, W^2 in the bias-correction
term, and unweighted residuals in the score construction. The Satterthwaite
DOF uses the full H1/H2/H3 array construction (`get_arrays.R::get_GH`), NOT
the simplified `(tr B)^2 / tr(B^2)` formula that works for the unweighted case.
"""

from __future__ import annotations

