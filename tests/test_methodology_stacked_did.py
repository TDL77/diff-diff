        np.testing.assert_array_equal(
            regen_ft,
            csv_ft,
            err_msg=(
                "DGP drift detected: generate_staggered_data(...) produces "
                "different treatment timing ('first_treat') than the committed "
                "CSV. Cohort assignment changed; regenerate CSV if intentional."
            ),
        )
